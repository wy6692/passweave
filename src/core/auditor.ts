import { BUILTIN_SITES } from './sites';
import type { AuditCheck, AuditReport, PatternSpec, SampleDiff } from './types';
import { weavePassword } from './weaver';

function computeSharedPrefixLen(a: string, b: string): number {
  const limit = Math.min(a.length, b.length);
  let i = 0;
  while (i < limit && a[i] === b[i]) i++;
  return i;
}

function computeSharedSuffixLen(a: string, b: string): number {
  const limit = Math.min(a.length, b.length);
  let i = 0;
  while (i < limit && a[a.length - 1 - i] === b[b.length - 1 - i]) i++;
  return i;
}

function computeLongestCommonSubstring(a: string, b: string): string {
  let longest = '';
  for (let i = 0; i < a.length; i++) {
    for (let j = i + 1; j <= a.length; j++) {
      const sub = a.slice(i, j);
      if (sub.length > longest.length && b.includes(sub)) {
        longest = sub;
      }
    }
  }
  return longest;
}

/**
 * Counts how many non-contiguous variable regions exist when comparing two passwords
 * generated by the same tier rule. Single-locus = 1 (e.g. `Head# Gt2 !84` vs `Head# Tb4 !84`),
 * multi-locus >= 2 (e.g. `G#Head:t284` vs `T#Head:b484`).
 */
function countDiffLoci(spec: PatternSpec): number {
  if (spec.topology === 'mirrored-split') return 2;
  return 1;
}

export function auditPatternSpec(spec: PatternSpec): AuditReport {
  const siteA = BUILTIN_SITES[0]!; // GitHub
  const siteB = BUILTIN_SITES[3]!; // Taobao
  const outA = weavePassword(spec, siteA, 'tier2');
  const outB = weavePassword(spec, siteB, 'tier2');

  const pwA = outA.password;
  const pwB = outB.password;

  const sharedPrefixLen = computeSharedPrefixLen(pwA, pwB);
  const sharedSuffixLen = computeSharedSuffixLen(pwA, pwB);
  const longestCommonSubstring = computeLongestCommonSubstring(pwA, pwB);
  const diffLociCount = countDiffLoci(spec);

  const sampleDiff: SampleDiff = {
    siteA,
    siteB,
    passwordA: pwA,
    passwordB: pwB,
    sharedPrefixLen,
    sharedSuffixLen,
    longestCommonSubstring,
    diffLociCount,
  };

  const checks: AuditCheck[] = [];

  // 1. Literal site name / prefix exposure check
  const lowerA = pwA.toLowerCase();
  const lowerB = pwB.toLowerCase();
  const leaksLiteral =
    lowerA.includes('git') ||
    lowerA.includes('hub') ||
    lowerB.includes('tao') ||
    lowerB.includes('bao') ||
    (spec.naming === 'pinyin' && spec.transform === 'outer-pair');

  checks.push({
    id: 'literal-leak',
    severity: leaksLiteral ? 'warn' : 'pass',
    score: leaksLiteral ? 55 : 100,
    titleEn: 'Lexical Domain Obfuscation',
    titleZh: '平台字面特征隐蔽度',
    detailEn: leaksLiteral
      ? 'Pinyin pair combined with Outer Pair leaves raw 2-letter initials intact (e.g. "Tb", "Wx"). An attacker who guesses Chinese initials can map the token.'
      : `Derived tokens ("${outA.siteToken}", "${outB.siteToken}") contain no dictionary substring of "${siteA.domainCore}" or "${siteB.domainCore}".`,
    detailZh: leaksLiteral
      ? '当前「双字拼音 + 极简首尾码」会直接保留原拼音缩写（如 Tb、Wx），若攻击者针对中文习惯建模较易猜出对应关系。'
      : `派生特征码（"${outA.siteToken}"、"${outB.siteToken}"）未暴露原域名连续词根，字典扫描器无法直接匹配网站名。`,
    ...(leaksLiteral
      ? {
          remediation: { transform: 'caesar-pair' },
          remediationLabelEn: 'Switch transform to Alphabet +1 Shift',
          remediationLabelZh: '切换为「前二字符顺移一位」消除字面关联',
        }
      : {}),
  });

  // 2. Prefix / suffix clustering resistance
  const maxAffixRatio = Math.max(sharedPrefixLen, sharedSuffixLen) / Math.max(pwA.length, 1);
  const hasLongStaticPrefix = sharedPrefixLen >= 4;
  const affixScore = hasLongStaticPrefix ? (maxAffixRatio > 0.6 ? 58 : 76) : 96;

  checks.push({
    id: 'affix-clustering',
    severity: sharedPrefixLen >= 6 ? 'warn' : 'pass',
    score: affixScore,
    titleEn: 'Prefix Clustering Resistance',
    titleZh: '前缀聚类抗性',
    detailEn:
      sharedPrefixLen === 0
        ? 'Zero shared prefix across sites. Passwords disperse across sorted breach dumps instead of grouping together.'
        : `Two leaked Tier-2 passwords share a ${sharedPrefixLen}-char prefix and ${sharedSuffixLen}-char suffix.`,
    detailZh:
      sharedPrefixLen === 0
        ? '不同站点密码实现零公共前缀，在按字母排序的脱库字典中完全打散，不会相邻暴露。'
        : `若两个日常级站点同时泄露，样本间共享 ${sharedPrefixLen} 位前缀与 ${sharedSuffixLen} 位后缀。`,
    ...(sharedPrefixLen >= 6
      ? {
          remediation: { topology: 'mirrored-split' },
          remediationLabelEn: 'Use Mirrored Token Split to eliminate static prefix',
          remediationLabelZh: '改用「经纬双点拆嵌式」打散固定前缀',
        }
      : {}),
  });

  // 3. Multi-locus dispersion + transform non-linearity
  const nonLinearBonus =
    spec.transform === 'consonant-count'
      ? 55
      : spec.transform === 'caesar-pair' || spec.transform === 'edge-length'
        ? 45
        : 25;
  const locusBonus = diffLociCount >= 2 ? 45 : 35;
  const dispersionScore = Math.min(100, nonLinearBonus + locusBonus);

  checks.push({
    id: 'locus-dispersion',
    severity: dispersionScore >= 75 ? 'pass' : 'warn',
    score: dispersionScore,
    titleEn: 'Differential Rule Induction Cost',
    titleZh: '多样本差分反推阻力',
    detailEn:
      diffLociCount >= 2
        ? `Variable site characters split across ${diffLociCount} non-adjacent positions, defeating single-slot template extractors.`
        : `Single variable slot (${spec.topology}) paired with ${spec.transform}. Strong against single leaks; switching to Mirrored Split resists two-sample diffing.`,
    detailZh:
      diffLociCount >= 2
        ? `网站变化特征被拆分至 ${diffLociCount} 处不相邻位置，单槽位模板提取脚本无法直接剥离。`
        : `当前为单槽位嵌入（${spec.topology}），单样本泄露难以反推；如需抵御多样本比对可升级为拆嵌拓扑。`,
    ...(dispersionScore < 75
      ? {
          remediation: { transform: 'consonant-count', topology: 'split-inlay' },
          remediationLabelEn: 'Upgrade to Consonant + Vowel Count transform',
          remediationLabelZh: '升级为「前二辅音 + 元音计数」非线性积木',
        }
      : {}),
  });

  // 4. Tier isolation verification (Tier 1 != Tier 2 != Tier 3)
  const tier1Pw = weavePassword(spec, BUILTIN_SITES[1]!, 'tier1').password;
  const decoyClean =
    spec.tier3Decoy.trim().length >= 8 &&
    !spec.tier3Decoy.toLowerCase().includes(spec.tier2.head.toLowerCase()) &&
    !spec.tier3Decoy.toLowerCase().includes(spec.tier1.head.toLowerCase());
  const tier1Distinct =
    spec.tier1.head.toLowerCase() !== spec.tier2.head.toLowerCase() && tier1Pw !== pwA;

  const isolationOk = decoyClean && tier1Distinct;
  checks.push({
    id: 'tier3-isolation',
    severity: isolationOk ? 'pass' : 'fail',
    score: isolationOk ? 100 : decoyClean || tier1Distinct ? 45 : 15,
    titleEn: 'Three-Tier Blast Radius Isolation',
    titleZh: '三级风险物理隔离校验',
    detailEn: isolationOk
      ? 'Tier 1 Vault, Tier 2 Standard, and Tier 3 Decoy share zero anchor substrings. High-risk forum breaches leak zero pattern data.'
      : !tier1Distinct
        ? 'Tier 1 (Core Vault) reuses the same anchor head as Tier 2. Compromise of Tier 2 could threaten banking/primary email.'
        : 'Tier 3 Decoy overlaps with your real anchor or is shorter than 8 characters.',
    detailZh: isolationOk
      ? '核心级、日常级与抛弃级口令彼此零词根重叠。高危小网站脱库不会泄露任何主公式线索。'
      : !tier1Distinct
        ? '核心级与日常级使用了相同的暗语词头！一旦日常规律被推理，主邮箱与金融账户将连带受胁。'
        : '抛弃级一次性口令包含了真实暗语片段或长度不足 8 位，存在关联泄露风险。',
    ...(!isolationOk
      ? {
          remediation: {
            tier1: { ...spec.tier1, head: `${spec.tier2.head}Vault`, tail: '91' },
            tier3Decoy: 'Pond-73-Mint!',
          },
          remediationLabelEn: 'Isolate Tier 1 & Tier 3 anchors',
          remediationLabelZh: '一键分离核心级暗语与抛弃级口令',
        }
      : {}),
  });

  // 5. Platform password policy compliance (length >= 12, upper, lower, digit, symbol, no 3x repeat)
  const hasUpper = /[A-Z]/.test(pwA);
  const hasLower = /[a-z]/.test(pwA);
  const hasDigit = /[0-9]/.test(pwA);
  const hasSymbol = /[^A-Za-z0-9]/.test(pwA);
  const noTripleRepeat = !/(.)\1\1/.test(pwA);
  const lengthOk = pwA.length >= 12;
  const lengthAcceptable = pwA.length >= 10;

  const classCount = [hasUpper, hasLower, hasDigit, hasSymbol].filter(Boolean).length;
  const compliancePass = lengthOk && classCount === 4 && noTripleRepeat;
  const complianceWarn = !compliancePass && lengthAcceptable && classCount >= 3;

  const missingPartsEn: string[] = [];
  const missingPartsZh: string[] = [];
  if (!lengthOk) {
    missingPartsEn.push(`length ${pwA.length}/12`);
    missingPartsZh.push(`当前长度 ${pwA.length} 位（建议 ≥12 位）`);
  }
  if (!hasUpper) {
    missingPartsEn.push('uppercase');
    missingPartsZh.push('缺少大写字母');
  }
  if (!hasLower) {
    missingPartsEn.push('lowercase');
    missingPartsZh.push('缺少小写字母');
  }
  if (!hasDigit) {
    missingPartsEn.push('digit');
    missingPartsZh.push('缺少数字');
  }
  if (!hasSymbol) {
    missingPartsEn.push('symbol');
    missingPartsZh.push('缺少特殊符号');
  }

  checks.push({
    id: 'policy-compliance',
    severity: compliancePass ? 'pass' : complianceWarn ? 'warn' : 'fail',
    score: compliancePass ? 100 : complianceWarn ? 70 : 35,
    titleEn: 'Strict Site Policy Compatibility',
    titleZh: '严苛平台密码策略兼容性',
    detailEn: compliancePass
      ? `${pwA.length} chars covering Uppercase, Lowercase, Digits, and Symbols. Passes 99% of enterprise/banking validators without forced rule exceptions.`
      : `May trigger site rejection (${missingPartsEn.join(', ')}), forcing ad-hoc password tweaks you might forget later.`,
    detailZh: compliancePass
      ? `生成长度 ${pwA.length} 位，完整覆盖大小写、数字与符号，无需因网站校验报错而临时改口令（临时破例是最常见的遗忘根源）。`
      : `部分严格站点可能报错（${missingPartsZh.join('、')}），迫使你注册时临时微调而导致日后遗忘。`,
    ...(!compliancePass
      ? {
          remediation: {
            tier2: {
              head: spec.tier2.head.length < 5 ? 'Cedar' : spec.tier2.head,
              tail: /\d/.test(spec.tier2.tail) && spec.tier2.tail.length >= 2 ? spec.tier2.tail : '84',
              sepA: '#',
              sepB: '!',
            },
          },
          remediationLabelEn: 'Pad anchor & delimiters to 12+ full-charset',
          remediationLabelZh: '补齐 12 位以上全字符集锚点配置',
        }
      : {}),
  });

  // 6. Human cognitive load & 6-month recall reliability
  const recallSec = outA.estimatedRecallSeconds;
  const anchorTooLong = spec.tier2.head.length + spec.tier2.tail.length > 14;
  const recallScore = anchorTooLong ? 68 : recallSec <= 3.0 ? 94 : 84;

  checks.push({
    id: 'cognitive-load',
    severity: anchorTooLong ? 'warn' : 'pass',
    score: recallScore,
    titleEn: 'Mental Compute & 6-Month Retention',
    titleZh: '心算耗时与半年留存度',
    detailEn: `Estimated mental assembly: ~${recallSec}s across 3 deterministic steps with canonical ${spec.naming} naming.`,
    detailZh: `预计熟练后脑内合成耗时约 ${recallSec} 秒（共 3 步确定性规则，采用「${spec.naming === 'domain' ? '主域名核心词' : '双字拼音首字母'}」唯一定名锚点）。`,
  });

  const securityIds = new Set([
    'literal-leak',
    'affix-clustering',
    'locus-dispersion',
    'tier3-isolation',
    'policy-compliance',
  ]);
  const securityChecks = checks.filter((c) => securityIds.has(c.id));
  const antiReversalScore = Math.round(
    securityChecks.reduce((acc, item) => acc + item.score, 0) / securityChecks.length,
  );

  const hasFail = checks.some((c) => c.severity === 'fail');
  const overallGrade: 'A' | 'B' | 'C' | 'D' = hasFail
    ? 'D'
    : antiReversalScore >= 88
      ? 'A'
      : antiReversalScore >= 75
        ? 'B'
        : 'C';

  return {
    antiReversalScore,
    recallEaseScore: recallScore,
    overallGrade,
    sampleDiff,
    checks,
  };
}

export function computeChecklistStatus(spec: PatternSpec) {
  const report = auditPatternSpec(spec);
  const findCheck = (id: string) => report.checks.find((c) => c.id === id);
  const literalOk = findCheck('literal-leak')?.severity === 'pass';
  const formatOk = findCheck('policy-compliance')?.severity === 'pass';
  const coreOk = findCheck('tier3-isolation')?.severity === 'pass';
  const prefixVaried = report.sampleDiff.sharedPrefixLen === 0;
  const passed = [literalOk, formatOk, coreOk, prefixVaried].filter(Boolean).length;
  const hasIssue = !literalOk || !formatOk || !coreOk;
  return { literalOk, formatOk, coreOk, prefixVaried, passed, total: 4, hasIssue };
}
